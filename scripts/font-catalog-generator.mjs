import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const FONT_FILE_SUFFIX = '.typeface.json';
const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(SCRIPT_DIR, '..');
const FONTS_DIR = path.join(PROJECT_ROOT, 'src', 'assets', 'fonts');
const OUTPUT_FILE = path.join(PROJECT_ROOT, 'src', 'fonts', 'catalog.generated.ts');

function toFontId(fileName) {
  const baseName = fileName.slice(0, -FONT_FILE_SUFFIX.length);
  const normalized = baseName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

  if (!normalized) {
    throw new Error(`Unable to derive font id from filename: ${fileName}`);
  }

  return normalized;
}

function toImportName(fontId) {
  const camelCase = fontId
    .split('-')
    .filter(Boolean)
    .map((part, index) => (index === 0 ? part : `${part[0].toUpperCase()}${part.slice(1)}`))
    .join('');

  return `${camelCase}FontUrl`;
}

function fallbackLabel(fontId) {
  return fontId
    .split('-')
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join(' ');
}

function getNestedValue(source, pathParts) {
  let current = source;

  for (const key of pathParts) {
    if (!current || typeof current !== 'object' || !(key in current)) {
      return undefined;
    }

    current = current[key];
  }

  return current;
}

function readString(value) {
  if (typeof value === 'string') {
    const trimmed = value.trim();
    return trimmed || undefined;
  }

  if (!value || typeof value !== 'object') {
    return undefined;
  }

  if (typeof value.en === 'string' && value.en.trim()) {
    return value.en.trim();
  }

  for (const localizedValue of Object.values(value)) {
    if (typeof localizedValue === 'string' && localizedValue.trim()) {
      return localizedValue.trim();
    }
  }

  return undefined;
}

function pickFirstString(source, candidatePaths) {
  for (const candidatePath of candidatePaths) {
    const value = getNestedValue(source, candidatePath);
    const asString = readString(value);
    if (asString) {
      return asString;
    }
  }

  return undefined;
}

function selectLabel(fontMeta, fontId) {
  const label = pickFirstString(fontMeta, [
    ['fullName'],
    ['original_font_information', 'fullName'],
    ['fontFamily'],
    ['original_font_information', 'fontFamily'],
    ['postScriptName'],
    ['original_font_information', 'postScriptName'],
  ]);

  return label ?? fallbackLabel(fontId);
}

async function readFontEntries() {
  const directoryEntries = await fs.readdir(FONTS_DIR, { withFileTypes: true });
  const fontFiles = directoryEntries
    .filter((entry) => entry.isFile() && entry.name.endsWith(FONT_FILE_SUFFIX))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));

  if (fontFiles.length === 0) {
    throw new Error(`No font files found in ${FONTS_DIR}`);
  }

  const ids = new Set();

  const entries = [];
  for (const fileName of fontFiles) {
    const filePath = path.join(FONTS_DIR, fileName);
    const source = await fs.readFile(filePath, 'utf8');
    const parsed = JSON.parse(source);
    const fontMeta = parsed && typeof parsed === 'object' ? parsed : {};

    const id = toFontId(fileName);
    if (ids.has(id)) {
      throw new Error(`Duplicate font id "${id}" derived from files in ${FONTS_DIR}`);
    }
    ids.add(id);

    entries.push({
      id,
      label: selectLabel(fontMeta, id),
      fileName,
      importName: toImportName(id),
    });
  }

  return entries;
}

function renderCatalog(entries) {
  const unionType = entries.map((entry) => `'${entry.id}'`).join(' | ');
  const defaultEntry = entries.find((entry) => entry.id === 'monda') ?? entries[0];

  const imports = entries
    .map((entry) => `import ${entry.importName} from '../assets/fonts/${entry.fileName}?url';`)
    .join('\n');

  const definitionItems = entries
    .map(
      (entry) => `  {
    id: '${entry.id}',
    label: ${JSON.stringify(entry.label)},
    url: ${entry.importName},
  },`,
    )
    .join('\n');

  return `/* eslint-disable */
// This file is auto-generated by scripts/font-catalog-generator.mjs.
// Do not edit manually.

${imports}

export type FontId = ${unionType};

export type FontDefinition = {
  id: FontId;
  label: string;
  url: string;
};

const FONT_DEFINITIONS: readonly FontDefinition[] = [
${definitionItems}
];

const FONT_DEFINITION_MAP: ReadonlyMap<FontId, FontDefinition> = new Map(
  FONT_DEFINITIONS.map((font) => [font.id, font]),
);

export const DEFAULT_FONT_ID: FontId = '${defaultEntry.id}';

export const FONT_OPTIONS: readonly { id: FontId; label: string }[] = FONT_DEFINITIONS.map((font) => ({
  id: font.id,
  label: font.label,
}));

export function getFontDefinition(fontId: FontId): FontDefinition {
  const definition = FONT_DEFINITION_MAP.get(fontId);
  if (!definition) {
    throw new Error(\`Unknown font id: \${fontId}\`);
  }

  return definition;
}

export function isFontId(value: string): value is FontId {
  return FONT_DEFINITION_MAP.has(value as FontId);
}
`;
}

export async function generateFontCatalog() {
  const entries = await readFontEntries();
  const nextContent = renderCatalog(entries);

  let previousContent;
  try {
    previousContent = await fs.readFile(OUTPUT_FILE, 'utf8');
  } catch (_error) {
    previousContent = undefined;
  }

  if (previousContent === nextContent) {
    return { changed: false, outputPath: OUTPUT_FILE };
  }

  await fs.writeFile(OUTPUT_FILE, nextContent, 'utf8');
  return { changed: true, outputPath: OUTPUT_FILE };
}

export function isFontAssetPath(filePath) {
  const normalizedPath = path.normalize(filePath);
  const fontsRoot = path.normalize(FONTS_DIR + path.sep);
  return normalizedPath.startsWith(fontsRoot) && normalizedPath.endsWith(FONT_FILE_SUFFIX);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateFontCatalog()
    .then((result) => {
      const status = result.changed ? 'updated' : 'up-to-date';
      console.log(`[font-catalog] ${status}: ${result.outputPath}`);
    })
    .catch((error) => {
      console.error('[font-catalog] generation failed');
      console.error(error);
      process.exitCode = 1;
    });
}
